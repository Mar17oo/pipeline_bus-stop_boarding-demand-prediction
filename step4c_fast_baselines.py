"""
STEP 4C — Fast-baseline supplement: MLR + XGBoost for the three pre-fix feature sets
======================================================================================
CONTEXT: results_summary_ai23_only.csv, _osm_only.csv, _ai23_osm.csv (dated 19 Jun)
were generated by an EARLIER version of step4_model.py, before the residual-skip /
Huber-loss / stratified-val bug fixes (see experiment_log.md, Experiment Set 1 "v1").
Re-running GATv2/MLP for those three feature sets would take ~3 more full 33-fold
runs (hours, CPU-only). Since MLR/RF/XGBoost/HistAvg are NOT affected by any of the
GATv2-specific bugs, this script computes just those four models for the three old
feature sets, using the EXACT SAME fold split / scaler protocol / seed as
step4_model.py. GATv2 and MLP numbers for these three columns are taken as-is from
the existing v1 result files — this is a known, documented caveat (see
experiment_log.md), not an oversight.

Run time: ~2-3 min total (no NN training, no graph building).
Output: results_cv_<tag>_fastbaselines.csv / results_summary_<tag>_fastbaselines.csv
        for tag in {ai23_only, osm_only, ai23_osm}
"""

import time
import warnings
warnings.filterwarnings("ignore")

import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestRegressor
from sklearn.linear_model import Ridge
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import mean_squared_error, mean_absolute_error
from xgboost import XGBRegressor

def log(msg):
    print(msg, flush=True)

BOROUGH_COL = "lad_name"
TARGET_COL  = "total_boardings"

FEAT_COLS = [
    "employment_all_30min", "hospitals_30min", "gp_30min",
    "supermarkets_30min",   "pharmacies_30min",
    "primary_schools_30min","secondary_schools_30min",
    "main_bua_30min",
]
OSM_COLS = ["poi_residential", "poi_shopping", "poi_company",
            "poi_education", "poi_entertainment", "poi_scenic"]
COORD_COLS = ["lat", "lon"]

RF_TREES = 150
SEED     = 42

CONFIGS = {
    "ai23_only": {"file": "stops_features.csv",     "feat": FEAT_COLS},
    "osm_only":  {"file": "stops_features_osm.csv",  "feat": OSM_COLS},
    "ai23_osm":  {"file": "stops_features_osm.csv",  "feat": FEAT_COLS + OSM_COLS},
}


def wmape(y_true, y_pred):
    return float(np.sum(np.abs(y_true - y_pred)) / (np.sum(np.abs(y_true)) + 1e-8))


def score(y_true, y_pred, name):
    y_pred = np.clip(y_pred, 0, None)
    return {
        "model": name,
        "WMAPE": round(wmape(y_true, y_pred), 4),
        "RMSE":  round(float(np.sqrt(mean_squared_error(y_true, y_pred))), 3),
        "MAE":   round(float(mean_absolute_error(y_true, y_pred)), 3),
    }


def prep_features(df, active_feat):
    active_all = active_feat + COORD_COLS
    X = np.zeros((len(df), len(active_all)), dtype=np.float32)
    for i, c in enumerate(active_feat):
        X[:, i] = np.log1p(df[c].values)
    X[:, len(active_feat)]     = df["lat"].values
    X[:, len(active_feat) + 1] = df["lon"].values
    return X


def run_tag(tag, cfg):
    log(f"\n{'='*76}\n{tag}  ({cfg['file']}, features={cfg['feat']})\n{'='*76}")
    df = pd.read_csv(cfg["file"])
    y_orig = df[TARGET_COL].values.astype(float)
    X_raw  = prep_features(df, cfg["feat"])
    boroughs = sorted(df[BOROUGH_COL].unique())

    rows = []
    t_start = time.time()
    for fi, borough in enumerate(boroughs):
        test_mask  = (df[BOROUGH_COL] == borough).values
        train_mask = ~test_mask
        tr_idx = np.where(train_mask)[0]
        te_idx = np.where(test_mask)[0]
        y_tr, y_te = y_orig[tr_idx], y_orig[te_idx]

        scaler = StandardScaler()
        X_sc_tr = scaler.fit_transform(X_raw[tr_idx])
        X_sc_te = scaler.transform(X_raw[te_idx])

        ha = score(y_te, np.full(len(te_idx), y_tr.mean()), "HistAvg")

        mlr = Ridge(alpha=1.0, random_state=SEED)
        mlr.fit(X_sc_tr, np.log1p(y_tr))
        mlr_s = score(y_te, np.expm1(mlr.predict(X_sc_te)), "MLR")

        rf = RandomForestRegressor(n_estimators=RF_TREES, max_features="sqrt",
                                   min_samples_leaf=5, n_jobs=-1, random_state=SEED)
        rf.fit(X_sc_tr, np.log1p(y_tr))
        rf_s = score(y_te, np.expm1(rf.predict(X_sc_te)), "RF")

        xgbr = XGBRegressor(n_estimators=300, max_depth=6, learning_rate=0.05,
                            random_state=SEED, n_jobs=-1, verbosity=0)
        xgbr.fit(X_sc_tr, np.log1p(y_tr))
        xgb_s = score(y_te, np.expm1(xgbr.predict(X_sc_te)), "XGBoost")

        base = {"borough": borough, "n_test": len(te_idx)}
        rows.extend([base | ha, base | mlr_s, base | rf_s, base | xgb_s])
        log(f"  [{fi+1:2d}/{len(boroughs)}] {borough:<30s} n={len(te_idx):4d}  "
            f"HA={ha['WMAPE']:.3f}  MLR={mlr_s['WMAPE']:.3f}  "
            f"RF={rf_s['WMAPE']:.3f}  XGB={xgb_s['WMAPE']:.3f}")

    results = pd.DataFrame(rows)
    results.to_csv(f"results_cv_{tag}_fastbaselines.csv", index=False)

    order = ["HistAvg", "MLR", "RF", "XGBoost"]
    agg = (results.groupby("model")[["WMAPE", "RMSE", "MAE"]]
           .agg(["mean", "std", "median"]).round(4))
    agg.columns = [f"{m}_{s}" for m, s in agg.columns]
    agg = agg.reset_index()
    agg["_o"] = agg["model"].map({m: i for i, m in enumerate(order)})
    agg = agg.sort_values("_o").drop(columns="_o")
    agg.to_csv(f"results_summary_{tag}_fastbaselines.csv", index=False)

    log(f"\n{tag} done in {(time.time()-t_start)/60:.1f} min")
    for _, r in agg.iterrows():
        log(f"  {r['model']:<8s} WMAPE={r['WMAPE_mean']:.4f}(+/-{r['WMAPE_std']:.4f})")


def main():
    for tag, cfg in CONFIGS.items():
        run_tag(tag, cfg)
    log("\nALL FAST-BASELINE SUPPLEMENTS DONE")


if __name__ == "__main__":
    main()
